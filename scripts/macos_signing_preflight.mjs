/** 临时原生签名预检，复用真实构建与签名函数，不创建候选、tag 或渠道发布。 */
import fs from 'node:fs';
import path from 'node:path';
import { commandRunner, gitIdentity, assertSourceStable, assertIgnored, runWorkspaceTests, cargoArguments } from '../.agents/skills/desktop-build-gpui-release/scripts/build_gpui_release.mjs';
import { readConfig, projectFacts } from '../.agents/skills/desktop-build-gpui-release/scripts/gpui_config.mjs';
import { safePath, sha256 } from '../.agents/skills/desktop-build-gpui-release/scripts/gpui_filesystem.mjs';
import { collectResources, stageResources, assertResourcesStable } from '../.agents/skills/desktop-build-gpui-release/scripts/gpui_resources.mjs';
import { releaseNotes, renderReleaseNotesRust, containsBytes } from '../.agents/skills/desktop-build-gpui-release/scripts/gpui_evidence.mjs';
import { packagerConfig, packagePath, verifyMacIdentity, verifyResources, verifyDmg } from '../.agents/skills/desktop-build-gpui-release/scripts/gpui_packager.mjs';
import { notarizationEnvironment, finalizeMacosSigning } from '../.agents/skills/desktop-build-gpui-release/scripts/gpui_macos_notarization.mjs';
import { requirePackager } from '../.agents/skills/desktop-build-gpui-release/scripts/gpui_global_tools.mjs';
import { assertDependencyLocks } from '../.agents/skills/desktop-implement-change/scripts/project_lock_policy.mjs';

const root = fs.realpathSync(process.cwd()), run = commandRunner(root);
if (process.platform !== 'darwin' || process.arch !== 'arm64') throw new Error('Native Apple Silicon runner is required');
const identity = gitIdentity(root,run);
if (identity.dirty) throw new Error('Preflight requires a clean committed source');
const config = readConfig(root);
const facts = projectFacts(root,JSON.parse(run('cargo',['metadata','--no-deps','--format-version','1']).stdout),config);
assertDependencyLocks(root,{rustTestManifests:facts.manifests});
assertIgnored(run,'target/gpui-packaging/.gpui-private');
fs.mkdirSync(path.join(root,'target/gpui-packaging'),{recursive:true});
const work = fs.mkdtempSync(path.join(root,'target/gpui-packaging/macos-preflight-'));
const target = 'aarch64-apple-darwin', notes = releaseNotes(root,facts.version);
const resources = collectResources(root,config,'macos',true);
const notesPath = path.join(work,'release_notes.rs');
fs.writeFileSync(notesPath,renderReleaseNotesRust(notes),{flag:'wx'});
const env = {...process.env,CARGO_TARGET_DIR:path.join(root,'target/gpui-packaging/cargo-cache'),CARGO_BUILD_TARGET:target,MACOSX_DEPLOYMENT_TARGET:config.macos.minimumSystemVersion};
for (const key of Object.keys(env)) if (/^(APPLE_|LM_NOTARIZATION_|CARGO_PACKAGER_)/u.test(key)) delete env[key];
env.HARNESS_GPUI_RELEASE_NOTES_RS = notesPath;
const unitTests = runWorkspaceTests(root,facts,run,env);
console.log(JSON.stringify({step:'native-tests',unitTests}));
assertSourceStable(root,run,identity);
const build = run('cargo',cargoArguments(['build','--release','--package',config.package,'--bin',config.binary,'--target',target,'--message-format','json-render-diagnostics'],facts.lockPolicy),{env});
const executables = build.stdout.split(/\r?\n/u).filter(Boolean).flatMap(line => {
  let item; try { item = JSON.parse(line); } catch { return []; }
  return item.reason === 'compiler-artifact' && item.target?.name === config.binary && item.executable ? [item.executable] : [];
});
if (executables.length !== 1) throw new Error('Expected one freshly built application executable');
const binary = safePath(env.CARGO_TARGET_DIR,path.relative(env.CARGO_TARGET_DIR,executables[0]),{type:'file'});
if (!containsBytes(binary,notes.bytes)) throw new Error('Embedded release notes are absent');
fs.mkdirSync(path.join(work,'binaries'));
fs.copyFileSync(binary,path.join(work,'binaries',config.binary));
stageResources(root,path.join(work,'resources'),resources);
const generated = packagerConfig({root,work,config,facts,target,format:'dmg',resources,signing:{selection:'enabled',source:'requested'},binarySha256:sha256(binary)});
const packagerFile = path.join(work,'packager.json');
fs.writeFileSync(packagerFile,JSON.stringify(generated,null,2)+'\n',{flag:'wx'});
const packageEnv = notarizationEnvironment(config,{...env,LM_NOTARIZATION_KEY_PATH:process.env.LM_NOTARIZATION_KEY_PATH,LM_NOTARIZATION_KEY_ID:process.env.LM_NOTARIZATION_KEY_ID,LM_NOTARIZATION_ISSUER:process.env.LM_NOTARIZATION_ISSUER,RUST_LOG:'info'});
delete packageEnv.CI;
const tool = requirePackager(root,run);
const packageResult = run(tool,['--verbose','--config',packagerFile],{env:packageEnv,quiet:true,timeout:40*60_000});
console.log('Native packager completed; verifying App and DMG receipts and tickets');
const app = packagePath(work,config,facts,target,'app'), artifact = packagePath(work,config,facts,target,'dmg');
verifyMacIdentity(run,app,config,facts);
verifyResources(path.join(app,'Contents/Resources'),root,resources);
const signing = finalizeMacosSigning({run,config,format:'dmg',artifact,app,env:packageEnv,packageResult});
const binarySha256 = sha256(safePath(app,`Contents/MacOS/${config.binary}`,{type:'file'}));
const resourceVerification = verifyDmg({run,artifact,mount:path.join(work,'mount'),root,config,facts,resources,binarySha256,env:packageEnv,developerSigned:true});
assertSourceStable(root,run,identity);
assertResourcesStable(root,config,'macos',true,resources);
const receipt = {mode:'local-preflight',distribution:'not-published',version:facts.version,sourceCommit:identity.commit,unitTests,...signing,resourceVerification,binarySha256,sha256:sha256(artifact)};
fs.writeFileSync(path.join(process.env.RUNNER_TEMP,'mac-native-probe.json'),JSON.stringify(receipt,null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify({step:'native-signing-preflight',status:'passed',sourceCommit:identity.commit,notarizationStatus:signing.notarizationStatus,resourceVerification}));
